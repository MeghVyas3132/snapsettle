// Generates src/generated.ts from the repo's deployments and compiled contracts, so the SDK's addresses and ABIs
// can never drift from what is deployed. Run from packages/sdk: `pnpm gen` (part of `pnpm build`).
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const dep = (step, key) => JSON.parse(readFileSync(join(root, "contracts/deployments/live", `${step}.json`), "utf8"))[key];
const abiOf = (name) => JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8")).abi;
const keep = (abi, names) => abi.filter((x) => names.includes(x.name));
const at = JSON.parse(readFileSync(join(root, "contracts/deployments/live/deployed-at.json"), "utf8"));

const out = {
  version: at.current,
  addresses: {
    originEscrow: dep("3-origin", "originEscrow"),
    resolver: dep("5-resolver", "snapsettleResolver"),
    destinationSettler: dep("1-destination", "destinationSettler"),
    reactive: dep("2-reactive", "snapsettleReactive"),
    tokenOrigin: "0x036CbD53842c5426634e7929541eC2318f3dCF7e",
    tokenDest: "0x31d0220469e10c4E71834a79b1f276d740d3768F",
  },
  abi: {
    escrow: keep(abiOf("OriginEscrow"), ["open", "openFor", "gaslessNonce", "orders", "requestRefund", "minInputAmount", "outflowCap", "inputToken", "outputToken", "Opened", "Settled", "Refunded", "SettleDeferred", "RefundRequested"]),
    settler: keep(abiOf("DestinationSettler"), ["fill", "confirm", "settleDelay", "tiers", "Filled", "Confirmed"]),
    reactive: keep(abiOf("SnapsettleReactive"), ["tiers", "settleDelay", "FillAccepted", "FillRejected", "FillConfirmed", "SettlementRequested"]),
    resolver: keep(abiOf("SnapsettleResolver"), ["resolve", "settleDelay"]),
  },
};
const missing = Object.entries(out.abi).flatMap(([k, a]) => (a.length ? [] : [k]));
if (missing.length) throw new Error(`empty ABI for ${missing}; run forge build first`);
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/generated.ts"),
  `// Generated by scripts/gen.mjs from contracts/deployments/live and contracts/out. Do not edit.\nexport const generated = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log(`sdk: generated for ${out.version}: escrow ${out.addresses.originEscrow}`);
